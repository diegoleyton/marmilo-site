function syncAppAccessDialog() {
  const isKids = currentAppProduct === "kids";
  const productName = isKids ? "MarMilo Kids" : "MarMilo Parents";

  if (appAccessTitle) {
    appAccessTitle.textContent = productName;
  }
  if (appAccessIcon) {
    appAccessIcon.src = isKids ? "./assets/kids_icon.png" : "./assets/parents_icon.png";
  }
  if (iosAppLink) {
    iosAppLink.href = iosLinks[currentAppProduct];
  }
  if (webAppLink) {
    webAppLink.href = isKids ? kidsLinks[currentLanguage] : parentsLinks[currentLanguage];
  }
  if (approvedAndroidLink) {
    const androidLink = androidLinks[currentAppProduct];
    approvedAndroidLink.hidden = !androidLink;
    approvedAndroidLink.href = androidLink || "#";
  }
  if (androidAccessForm) {
    androidAccessForm.elements.product.value = currentAppProduct;
    androidAccessForm.elements.language.value = currentLanguage;
  }
}

