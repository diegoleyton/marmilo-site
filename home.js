let currentLanguage = "en";
let pendingFormSubmission = null;
let feedbackClientId = "";
let sectionNavUpdateQueued = false;
let currentActiveSectionLink = null;
let currentAppProduct = "parents";

bootstrap();

function bootstrap() {
  langButtons.forEach((button) => {
    button.addEventListener("click", () => setLanguage(button.dataset.lang || "en"));
  });

  feedbackOpenButton?.addEventListener("click", openFeedbackDialog);
  feedbackCloseButton?.addEventListener("click", closeFeedbackDialog);
  feedbackDialog?.addEventListener("click", (event) => {
    if (event.target === feedbackDialog) {
      closeFeedbackDialog();
    }
  });
  feedbackForm?.addEventListener("submit", submitFeedback);
  [...parentsLinkNodes, ...kidsLinkNodes].forEach((link) => {
    link.addEventListener("click", (event) => {
      event.preventDefault();
      openAppAccessDialog(link.matches(selectors.parentsLinks) ? "parents" : "kids");
    });
  });
  appAccessCloseButton?.addEventListener("click", closeAppAccessDialog);
  appAccessDialog?.addEventListener("click", (event) => {
    if (event.target === appAccessDialog) {
      closeAppAccessDialog();
    }
  });
  androidRequestOpenButton?.addEventListener("click", showAndroidAccessForm);
  androidAccessForm?.addEventListener("submit", submitAndroidAccessRequest);
  presentationPlayButton?.addEventListener("click", playPresentationVideo);
  window.addEventListener("message", handleFeedbackResponse);
  window.addEventListener("scroll", queueSectionNavUpdate, { passive: true });
  window.addEventListener("resize", () => {
    queueSectionNavUpdate();
    keepActiveSectionLinkVisible(currentActiveSectionLink);
  });
  sectionNavLinks.forEach((link) => {
    link.addEventListener("click", () => setActiveSectionLink(link));
  });

  randomizeDecorationTiming();
  startHeroKidsRotation();
  setLanguage(getPreferredLanguage());
  updateActiveSectionNav();
}

function playPresentationVideo() {
  if (!presentationPlayer) {
    return;
  }

  const iframe = document.createElement("iframe");
  iframe.src = "https://www.youtube-nocookie.com/embed/WGspX1MzJJQ?autoplay=1&rel=0";
  iframe.title = "MarMilo presentation";
  iframe.allow = "accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share";
  iframe.referrerPolicy = "strict-origin-when-cross-origin";
  iframe.allowFullscreen = true;
  presentationPlayer.replaceChildren(iframe);
}

function startHeroKidsRotation() {
  if (!heroKidsImage || !heroKidsNextImage) {
    return;
  }

  const sources = ["a", "b", "c", "d", "e", "f"]
    .map((variant) => `./assets/decoration/kids_${variant}.png`);
  let currentIndex = Math.floor(Math.random() * sources.length);
  let activeImage = heroKidsImage;
  let standbyImage = heroKidsNextImage;

  activeImage.src = sources[currentIndex];
  standbyImage.src = sources[(currentIndex + 1) % sources.length];

  if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) {
    return;
  }

  sources.forEach((source) => {
    const image = new Image();
    image.src = source;
  });

  const scheduleNextImage = () => {
    const holdDuration = 6000 + Math.random() * 2000;
    window.setTimeout(showNextImage, holdDuration);
  };

  const showNextImage = () => {
    const nextIndex = (currentIndex + 1) % sources.length;
    const nextSource = sources[nextIndex];
    standbyImage.src = nextSource;

    const revealNextImage = () => {
      activeImage.classList.remove("is-visible");
      standbyImage.classList.add("is-visible");

      window.setTimeout(() => {
        const previousImage = activeImage;
        activeImage = standbyImage;
        standbyImage = previousImage;
        currentIndex = nextIndex;
        scheduleNextImage();
      }, 850);
    };

    if (standbyImage.decode) {
      standbyImage.decode().then(revealNextImage).catch(revealNextImage);
    } else {
      revealNextImage();
    }
  };

  scheduleNextImage();
}

function randomizeDecorationTiming() {
  const decorations = document.querySelectorAll([
    ".frame-decoration",
    ".section-nav",
    ".hero-copy",
    ".section > .section-details.section-static",
    ".contact-panel",
    ".link-button",
    ".button"
  ].join(","));

  decorations.forEach((decoration) => {
    const duration = 1.4 + Math.random() * 1.2;
    const delay = -Math.random() * duration;
    decoration.style.setProperty("--decoration-duration", `${duration.toFixed(2)}s`);
    decoration.style.setProperty("--decoration-delay", `${delay.toFixed(2)}s`);
  });
}

function queueSectionNavUpdate() {
  if (sectionNavUpdateQueued) {
    return;
  }

  sectionNavUpdateQueued = true;
  window.requestAnimationFrame(() => {
    sectionNavUpdateQueued = false;
    updateActiveSectionNav();
  });
}

function updateActiveSectionNav() {
  if (!sectionNav || !sectionNavTargets.length) {
    return;
  }

  const readingLine = sectionNav.getBoundingClientRect().bottom + Math.min(window.innerHeight * 0.18, 140);
  const activeTarget = sectionNavTargets.find(({ section }) => {
    const bounds = section.getBoundingClientRect();
    return bounds.top <= readingLine && bounds.bottom > readingLine;
  });

  setActiveSectionLink(activeTarget?.link || null);
}

function setActiveSectionLink(activeLink) {
  const activeLinkChanged = activeLink !== currentActiveSectionLink;
  currentActiveSectionLink = activeLink;

  sectionNavLinks.forEach((link) => {
    const isActive = link === activeLink;
    link.classList.toggle("is-active", isActive);

    if (isActive) {
      link.setAttribute("aria-current", "location");
    } else {
      link.removeAttribute("aria-current");
    }
  });

  if (activeLinkChanged) {
    keepActiveSectionLinkVisible(activeLink);
  }
}

function keepActiveSectionLinkVisible(activeLink) {
  if (!activeLink || !sectionNavLinksContainer || window.innerWidth > 767) {
    return;
  }

  const containerBounds = sectionNavLinksContainer.getBoundingClientRect();
  const linkBounds = activeLink.getBoundingClientRect();
  const edgePadding = 8;
  let scrollDelta = 0;

  if (linkBounds.left < containerBounds.left + edgePadding) {
    scrollDelta = linkBounds.left - containerBounds.left - edgePadding;
  } else if (linkBounds.right > containerBounds.right - edgePadding) {
    scrollDelta = linkBounds.right - containerBounds.right + edgePadding;
  }

  if (scrollDelta === 0) {
    return;
  }

  const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  sectionNavLinksContainer.scrollBy({
    left: scrollDelta,
    behavior: reduceMotion ? "auto" : "smooth"
  });
}

function setLanguage(language) {
  currentLanguage = copy[language] ? language : "en";
  const dict = copy[currentLanguage];

  translatedNodes.forEach((node) => {
    const key = node.dataset.i18n;
    const attr = node.dataset.i18nAttr;

    if (!key || !dict[key]) {
      return;
    }

    if (attr === "text") {
      node.textContent = dict[key];
      return;
    }

    if (attr === "html") {
      node.innerHTML = dict[key];
      return;
    }

    if (attr) {
      node.setAttribute(attr, dict[key]);
      return;
    }

    node.textContent = dict[key];
  });

  parentsLinkNodes.forEach((node) => {
    node.href = parentsLinks[currentLanguage];
  });

  kidsLinkNodes.forEach((node) => {
    node.href = kidsLinks[currentLanguage];
  });

  document.documentElement.lang = currentLanguage;
  document.title = pageTitles[currentLanguage];

  langButtons.forEach((button) => {
    const isActive = button.dataset.lang === currentLanguage;
    button.classList.toggle("is-active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  if (feedbackForm) {
    feedbackForm.elements.language.value = currentLanguage;
  }

  if (androidAccessForm) {
    androidAccessForm.elements.language.value = currentLanguage;
  }

  syncAppAccessDialog();
}

function openAppAccessDialog(product) {
  if (!appAccessDialog) {
    return;
  }

  currentAppProduct = product === "kids" ? "kids" : "parents";
  androidAccessForm?.reset();
  androidAccessForm?.setAttribute("hidden", "");
  if (androidAccessStatus) {
    androidAccessStatus.textContent = "";
  }
  syncAppAccessDialog();
  appAccessDialog.showModal();
  window.requestAnimationFrame(() => appAccessCloseButton?.focus());
}

function closeAppAccessDialog() {
  appAccessDialog?.close();
}

function syncAppAccessDialog() {
  const isKids = currentAppProduct === "kids";
  const productName = isKids ? "MarMilo Kids" : "MarMilo Parents";

  if (appAccessTitle) {
    appAccessTitle.textContent = productName;
  }
  if (appAccessIcon) {
    appAccessIcon.src = isKids ? "./assets/kids_icon.png" : "./assets/parents_icon.png";
  }
  if (iosAppLink) {
    iosAppLink.href = iosLinks[currentAppProduct];
  }
  if (webAppLink) {
    webAppLink.href = isKids ? kidsLinks[currentLanguage] : parentsLinks[currentLanguage];
  }
  if (approvedAndroidLink) {
    const androidLink = androidLinks[currentAppProduct];
    approvedAndroidLink.hidden = !androidLink;
    approvedAndroidLink.href = androidLink || "#";
  }
  if (androidAccessForm) {
    androidAccessForm.elements.product.value = currentAppProduct;
    androidAccessForm.elements.language.value = currentLanguage;
  }
}

function showAndroidAccessForm() {
  if (!androidAccessForm) {
    return;
  }

  androidAccessForm.removeAttribute("hidden");
  if (androidAccessStatus) {
    androidAccessStatus.textContent = "";
  }
  window.requestAnimationFrame(() => androidAccessForm.elements.email.focus());
}

function openFeedbackDialog() {
  if (!feedbackDialog) {
    return;
  }

  feedbackStatus.textContent = "";
  feedbackDialog.showModal();
  window.requestAnimationFrame(() => feedbackForm?.elements.title.focus());
}

function closeFeedbackDialog() {
  feedbackDialog?.close();
}

function submitFeedback(event) {
  if (!feedbackForm || !feedbackStatus) {
    return;
  }

  submitSheetForm(event, feedbackForm, feedbackStatus, {
    sending: "feedbackSending",
    success: "feedbackSuccess",
    error: "feedbackError",
    rateLimited: "feedbackRateLimited",
    setupRequired: "feedbackSetupRequired"
  });
}

function submitAndroidAccessRequest(event) {
  if (!androidAccessForm || !androidAccessStatus) {
    return;
  }

  const email = androidAccessForm.elements.email.value.trim();
  const productName = currentAppProduct === "kids" ? "MarMilo Kids" : "MarMilo Parents";
  androidAccessForm.elements.product.value = currentAppProduct;
  androidAccessForm.elements.title.value = `Android access request - ${productName}`;
  androidAccessForm.elements.description.value = `Google Play email: ${email}\nProduct: ${productName}`;

  submitSheetForm(event, androidAccessForm, androidAccessStatus, {
    sending: "androidAccessSending",
    success: "androidAccessSuccess",
    error: "androidAccessError",
    rateLimited: "androidAccessRateLimited",
    setupRequired: "feedbackSetupRequired"
  }, () => syncAppAccessDialog());
}

function submitSheetForm(event, form, status, messages, onSuccess) {
  if (!feedbackEndpoint) {
    event.preventDefault();
    status.textContent = copy[currentLanguage][messages.setupRequired];
    return;
  }

  if (pendingFormSubmission) {
    event.preventDefault();
    return;
  }

  const submissionId = createSubmissionId();
  form.action = feedbackEndpoint;
  form.elements.language.value = currentLanguage;
  form.elements.page.value = window.location.href;
  form.elements.clientId.value = getFeedbackClientId();
  form.elements.submissionId.value = submissionId;
  status.textContent = copy[currentLanguage][messages.sending];
  form.querySelector("button[type='submit']").disabled = true;

  pendingFormSubmission = {
    form,
    status,
    messages,
    onSuccess,
    submissionId,
    timeout: window.setTimeout(() => finishFormSubmission(false, "timeout"), 15000)
  };
}

function handleFeedbackResponse(event) {
  const result = event.data;

  if (
    !pendingFormSubmission ||
    !result ||
    result.source !== "marmilo-feedback" ||
    result.submissionId !== pendingFormSubmission.submissionId
  ) {
    return;
  }

  finishFormSubmission(Boolean(result.ok), result.error || "");
}

function finishFormSubmission(succeeded, errorCode) {
  if (!pendingFormSubmission) {
    return;
  }

  const { form, status, messages, onSuccess, timeout } = pendingFormSubmission;
  window.clearTimeout(timeout);
  pendingFormSubmission = null;
  form.querySelector("button[type='submit']").disabled = false;

  if (succeeded) {
    form.reset();
    form.elements.language.value = currentLanguage;
    status.textContent = copy[currentLanguage][messages.success];
    onSuccess?.();
    return;
  }

  status.textContent = errorCode === "rate_limited"
    ? copy[currentLanguage][messages.rateLimited]
    : copy[currentLanguage][messages.error];
}

function getFeedbackClientId() {
  const storageKey = "marmilo-feedback-client";

  if (feedbackClientId) {
    return feedbackClientId;
  }

  try {
    feedbackClientId = window.localStorage.getItem(storageKey) || "";

    if (!feedbackClientId) {
      feedbackClientId = createSubmissionId();
      window.localStorage.setItem(storageKey, feedbackClientId);
    }
  } catch (error) {
    feedbackClientId = createSubmissionId();
  }

  return feedbackClientId;
}

function createSubmissionId() {
  if (window.crypto?.randomUUID) {
    return window.crypto.randomUUID();
  }

  return `${Date.now()}-${Math.random().toString(36).slice(2)}`;
}

function getPreferredLanguage() {
  const locale = (navigator.language || navigator.userLanguage || "").toLowerCase();

  if (locale.startsWith("es")) {
    return "es";
  }

  if (locale.startsWith("en")) {
    return "en";
  }

  return "en";
}
