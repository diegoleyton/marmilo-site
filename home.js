function submitSheetForm(event, form, status, messages, onSuccess) {
  if (!feedbackEndpoint) {
    event.preventDefault();
    status.textContent = copy[currentLanguage][messages.setupRequired];
    return;
  }

  if (pendingFormSubmission) {
    event.preventDefault();
    return;
  }

  const submissionId = createSubmissionId();
  form.action = feedbackEndpoint;
  form.elements.language.value = currentLanguage;
  form.elements.page.value = window.location.href;
  form.elements.clientId.value = getFeedbackClientId();
  form.elements.submissionId.value = submissionId;
  status.textContent = copy[currentLanguage][messages.sending];
  form.querySelector("button[type='submit']").disabled = true;

  pendingFormSubmission = {
    form,
    status,
    messages,
    onSuccess,
    submissionId,
    timeout: window.setTimeout(() => finishFormSubmission(false, "timeout"), 15000)
  };
}

function handleFeedbackResponse(event) {
  const result = event.data;

  if (
    !pendingFormSubmission ||
    !result ||
    result.source !== "marmilo-feedback" ||
    result.submissionId !== pendingFormSubmission.submissionId
  ) {
    return;
  }

  finishFormSubmission(Boolean(result.ok), result.error || "");
}

function finishFormSubmission(succeeded, errorCode) {
  if (!pendingFormSubmission) {
    return;
  }

  const { form, status, messages, onSuccess, timeout } = pendingFormSubmission;
  window.clearTimeout(timeout);
  pendingFormSubmission = null;
  form.querySelector("button[type='submit']").disabled = false;

  if (succeeded) {
    form.reset();
    form.elements.language.value = currentLanguage;
    status.textContent = copy[currentLanguage][messages.success];
    onSuccess?.();
    return;
  }

  status.textContent = errorCode === "rate_limited"
    ? copy[currentLanguage][messages.rateLimited]
    : copy[currentLanguage][messages.error];
}

function getFeedbackClientId() {
  const storageKey = "marmilo-feedback-client";

  if (feedbackClientId) {
    return feedbackClientId;
  }

  try {
    feedbackClientId = window.localStorage.getItem(storageKey) || "";

    if (!feedbackClientId) {
      feedbackClientId = createSubmissionId();
      window.localStorage.setItem(storageKey, feedbackClientId);
    }
  } catch (error) {
    feedbackClientId = createSubmissionId();
  }

  return feedbackClientId;
}

function createSubmissionId() {
  if (window.crypto?.randomUUID) {
    return window.crypto.randomUUID();
  }

  return `${Date.now()}-${Math.random().toString(36).slice(2)}`;
}

function getPreferredLanguage() {
  const locale = (navigator.language || navigator.userLanguage || "").toLowerCase();

  if (locale.startsWith("es")) {
    return "es";
  }

  if (locale.startsWith("en")) {
    return "en";
  }

  return "en";
}
