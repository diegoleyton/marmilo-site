function bootstrap() {
  langButtons.forEach((button) => {
    button.addEventListener("click", () => setLanguage(button.dataset.lang || "en"));
  });

  feedbackOpenButton?.addEventListener("click", openFeedbackDialog);
  feedbackCloseButton?.addEventListener("click", closeFeedbackDialog);
  feedbackDialog?.addEventListener("click", (event) => {
    if (event.target === feedbackDialog) {
      closeFeedbackDialog();
    }
  });
  feedbackForm?.addEventListener("submit", submitFeedback);
  [...parentsLinkNodes, ...kidsLinkNodes].forEach((link) => {
    link.addEventListener("click", (event) => {
      event.preventDefault();
      openAppAccessDialog(link.matches(selectors.parentsLinks) ? "parents" : "kids");
    });
  });
  appAccessCloseButton?.addEventListener("click", closeAppAccessDialog);
  appAccessDialog?.addEventListener("click", (event) => {
    if (event.target === appAccessDialog) {
      closeAppAccessDialog();
    }
  });
  androidRequestOpenButton?.addEventListener("click", showAndroidAccessForm);
  androidAccessForm?.addEventListener("submit", submitAndroidAccessRequest);
  presentationPlayButton?.addEventListener("click", playPresentationVideo);
  window.addEventListener("message", handleFeedbackResponse);
  window.addEventListener("scroll", queueSectionNavUpdate, { passive: true });
  window.addEventListener("resize", () => {
    queueSectionNavUpdate();
    keepActiveSectionLinkVisible(currentActiveSectionLink);
  });
  sectionNavLinks.forEach((link) => {
    link.addEventListener("click", () => setActiveSectionLink(link));
  });

  randomizeDecorationTiming();
  startHeroKidsRotation();
  setLanguage(getPreferredLanguage());
  updateActiveSectionNav();
}

